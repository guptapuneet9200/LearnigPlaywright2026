
// Comparison Operator (will always result in boolean i.e. True and false)
// = -> Assignment Operator
// == -> Loose comparison Operator
// === ->  Strict comparison Operator
// >, < , <=, >=, !, !==

console.log(3 > 4)
console.log(3 < 4)
console.log(4 >= 4) // It mean 4>4 or 4==4 (OR Gate operator)
console.log(3 <= 4)

console.log("---------")
console.log(5 == "5")  // Loose couple comparison
console.log(5 === "5") // Strict comparison

console.log("---------")
console.log(5 != "5"); // false , 5 = int, "5" = string, both  of them are not equal ? Loose couple
console.log(5 !== "5"); // true 
